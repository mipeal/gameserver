#!/usr/bin/env python3
"""Generate the TEAMS/SIM_VPN-dependent compose files for the simulation
deployment:

- simulation/docker-compose.vulnboxes.yml — one vulnbox-N per team at
  10.32.N.2 on simnet (always)
- simulation/docker-compose.sim-vpn.yml — wg caps/mounts/sim-init/vpnboard
  (only when SIM_VPN=1)

Run: python3 rust/simulation/gen_compose.py --env rust/simulation/.env.sim
     (--check emits to stdout; test_gen.py exercises it)
"""
import argparse
import sys
from pathlib import Path

HEADER = "# generated by gen_compose.py — do not edit\n"


def parse_env(path):
    env = {}
    for line in Path(path).read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, _, value = line.partition("=")
            env[key.strip()] = value.strip()
    return env


def gen_vulnboxes(teams, vpn=False):
    # SIM_VPN=1: the wg tunnel owns 10.32.0.0/16 (team.vpn = 10.32.N.2 must
    # route into wg0), so the bridge moves to 10.33.0.0/16
    base = "10.33" if vpn else "10.32"
    out = [HEADER, "services:\n"]
    for n in range(1, teams + 1):
        out.append(f"""  vulnbox-{n}:
    image: sim-vulnbox
    build:
      context: ./simulation/vulnbox
      dockerfile: Dockerfile.vulnbox
    environment:
      TEAM_ID: "{n}"
      SIM_PORTS: "1337,8080,31337"
      TEAMS: "{teams}"
      SIM_ATTACK_RATE: "${{SIM_ATTACK_RATE:-0.25}}"
      SUBMITTER_ADDR: submitter:31337
      SCOREBOARD_ADDR: scoreboard:80
    networks:
      simnet:
        ipv4_address: {base}.{n}.2
    restart: unless-stopped
""")
    out.append(f"""networks:
  simnet:
    ipam:
      config:
        - subnet: {base}.0.0/16
          gateway: {base}.0.1
""")
    return "".join(out)


def gen_sim_vpn(teams):
    vpn_entries = []
    for n in range(1, teams + 1):
        vpn_entries.append(f"""  vulnbox-{n}:
    cap_add:
      - NET_ADMIN
    devices:
      - /dev/net/tun
    volumes:
      - keys:/run/sim/keys:ro
      - ./simulation/wg:/sim/wg:ro
""")
    out = [HEADER, "services:\n"]
    out.extend(vpn_entries)
    out.append(f"""  sim-init:
    image: gameserver-sim
    restart: "no"
    environment:
      TEAMS: "{teams}"
    volumes:
      - wg-keystore:/run/sim/wg
      - keys:/run/sim/keys
      - ./simulation/wg:/opt/sim/wg:ro
    command:
      - sh
      - -c
      # wireguard-sync has no CONFIG env here, so it writes ./keystore.json
      # (cwd /opt) — copy it into the keystore volume for split-keystore.py
      - wireguard-sync generate -a $((TEAMS + 1)) && cp /opt/keystore.json /run/sim/wg/ && python3 /opt/sim/wg/split-keystore.py
    networks: [simnet]

  controlserver:
    cap_add:
      - NET_ADMIN
    devices:
      - /dev/net/tun
    environment:
      TEAMS: "{teams}"  # server-setup.sh: one wg peer per team
    volumes:
      - keys:/run/sim/keys:ro
      - ./simulation/wg:/opt/sim/wg:ro
    command:
      - sh
      - -c
      - /opt/sim/wg/server-setup.sh; exec /usr/local/bin/controlserver
    ports:
      - "51820/udp"

  vpnboard:
    image: gameserver-sim
    environment:
      CONFIG: /opt/sim/config.sim.yaml
      POSTGRES_SERVER: postgres
      POSTGRES_PORT: "5432"
      POSTGRES_DATABASE: saarctf
      POSTGRES_USERNAME: saarctf
      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD:-demo}}
      REDIS_HOST: redis
      REDIS_PORT: "6379"
      SCOREBOARD_PATH: /var/scoreboard
      VPNBOARD_PATH: /tmp/vpnboard
    volumes:
      - ./simulation/config.sim.yaml:/opt/sim/config.sim.yaml:ro
    # --daemon: default is run-once-and-exit; --complete --check-wg: single router sees all
    command: ["/usr/local/bin/vpn-status-daemon", "--daemon", "--complete", "--check-wg"]
    network_mode: "service:controlserver"
    restart: unless-stopped
    depends_on:
      controlserver:
        condition: service_started

volumes:
  keys:
  wg-keystore:
""")
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", required=True, help=".env file with TEAMS / SIM_VPN")
    # parse_args consumes argv (tests pass a list); None = sys.argv
    ap.add_argument("--out-dir", default=str(Path(__file__).parent))
    ap.add_argument("--check", action="store_true", help="print to stdout only")
    args = ap.parse_args(argv)

    env = parse_env(args.env)
    teams = int(env.get("TEAMS", "8"))
    sim_vpn = env.get("SIM_VPN", "1") == "1"

    vulnboxes = gen_vulnboxes(teams, vpn=sim_vpn)
    if args.check:
        print(vulnboxes)
        if sim_vpn:
            print(gen_sim_vpn(teams))
        return 0

    out = Path(args.out_dir)
    (out / "docker-compose.vulnboxes.yml").write_text(vulnboxes)
    if sim_vpn:
        (out / "docker-compose.sim-vpn.yml").write_text(gen_sim_vpn(teams))
    else:
        (out / "docker-compose.sim-vpn.yml").unlink(missing_ok=True)
    print(f"generated: docker-compose.vulnboxes.yml"
          f"{', docker-compose.sim-vpn.yml' if sim_vpn else ''} (TEAMS={teams}, SIM_VPN={int(sim_vpn)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
